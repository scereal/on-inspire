// Practice player: picks a verified problem from the bank and runs its steps.
(function () {
  const $ = (id) => document.getElementById(id);
  const params = new URLSearchParams(location.search);
  const fwId = params.get("f");
  const level = Number(params.get("level") || 1);

  const store = {
    get(k, fallback) { try { const v = localStorage.getItem(k); return v ? JSON.parse(v) : fallback; } catch { return fallback; } },
    set(k, v) { try { localStorage.setItem(k, JSON.stringify(v)); } catch {} },
  };
  const h = (tag, props = {}, ...kids) => {
    const n = Object.assign(document.createElement(tag), props);
    n.append(...kids);
    return n;
  };
  const math = (node) => {
    if (window.renderMathInElement) {
      window.renderMathInElement(node, { delimiters: [{ left: "$$", right: "$$", display: true }, { left: "$", right: "$", display: false }], throwOnError: false });
    }
    return node;
  };
  const say = (box, kind, html) => { box.className = `feedback ${kind}`; box.innerHTML = html; math(box); };

  // Picker: no framework chosen ---------------------------------------------------
  async function picker() {
    $("title").textContent = "Practice";
    $("lede").textContent = "Pick a topic and a level. Every problem is generated by code and verified before it gets here.";
    $("stage").hidden = true;
    const res = await fetch("../bank/index.json").catch(() => null);
    if (!res || !res.ok) return say($("task"), "bad", "Couldn't load the list of topics. Check your connection and reload.");
    const index = await res.json();
    const list = h("ul", { className: "topics" });
    for (const [id, fw] of Object.entries(index)) {
      const levels = h("div", { className: "levels" });
      for (const [n, info] of Object.entries(fw.levels)) {
        levels.append(h("a", { href: `?f=${id}&level=${n}`, textContent: `${n}. ${info.name}` }));
      }
      list.append(h("li", {}, h("h2", { textContent: fw.title }), h("p", { textContent: fw.outcome }), levels));
    }
    $("task").replaceChildren(list);
  }

  // One problem --------------------------------------------------------------------
  let bank, problem, scene, current, firstTry;

  async function start() {
    const res = await fetch(`../bank/${fwId}-${level}.json`).catch(() => null);
    if (!res || !res.ok) {
      $("stage").hidden = true;
      $("title").textContent = "Practice";
      $("task").replaceChildren(h("p", { className: "feedback bad", innerHTML: `This level isn't available yet. <a href="./">Choose another topic</a>.` }));
      return;
    }
    bank = await res.json();
    document.title = `${bank.title}: Practice`;
    $("title").textContent = bank.title;
    $("crumb-topic").textContent = `${bank.title}, level ${level}`;
    next();
  }

  function next() {
    const key = `seen:${fwId}-${level}`;
    let seen = store.get(key, []);
    let pool = bank.problems.filter((p) => !seen.includes(p.id));
    if (!pool.length) { seen = []; pool = bank.problems; }
    problem = pool[Math.floor(Math.random() * pool.length)];
    store.set(key, [...seen, problem.id]);
    firstTry = true;
    $("lede").textContent = `Level ${level}: ${bank.level_name}`;
    $("story").innerHTML = problem.story;
    math($("story"));
    $("stage").hidden = false;
    $("stage").dataset.problem = problem.id;
    scene = window.Scenes[problem.scene.type]($("scene"), problem);
    math($("scene"));
    go(0);
  }

  function rail() {
    $("steps").replaceChildren(...problem.steps.map((_, i) => {
      const b = h("button", { type: "button", textContent: i + 1, disabled: i > current });
      b.setAttribute("aria-label", `Step ${i + 1}`);
      if (i === current) b.setAttribute("aria-current", "step");
      if (i < current) b.classList.add("done");
      return b;
    }));
  }

  function go(i) {
    current = i;
    rail();
    const step = problem.steps[i];
    const fb = h("div", { className: "feedback", role: "status" });
    const prompt = math(h("p", { className: "prompt", innerHTML: step.prompt }));
    const body = render(step, fb);
    $("task").replaceChildren(h("h2", { textContent: `Step ${i + 1} of ${problem.steps.length}` }), prompt, body, fb);
  }

  function correct(fb, step) {
    say(fb, "good", `<strong>Right.</strong> ${step.explain || ""}`);
    if (scene.bench) scene.bench.disable();
    const last = current === problem.steps.length - 1;
    const btn = h("button", { type: "button", className: last ? "primary" : "", textContent: last ? "Finish" : "Next step" });
    btn.addEventListener("click", () => (last ? finish() : go(current + 1)));
    $("task").append(h("div", { className: "row" }, btn));
    btn.focus();
  }

  function wrong(fb, html) {
    firstTry = false;
    say(fb, "bad", html);
  }

  function render(step, fb) {
    if (step.format === "choice") {
      const wrap = h("div", { className: "choices" });
      for (const o of step.options) {
        const b = math(h("button", { type: "button", innerHTML: o.label }));
        b.addEventListener("click", () => {
          if (o.correct) {
            b.classList.add("right");
            wrap.querySelectorAll("button").forEach((x) => (x.disabled = x !== b));
            correct(fb, step);
          } else {
            b.classList.add("wrong");
            wrong(fb, o.feedback || bank.misconceptions[o.misconception] || "Not quite. Try another.");
          }
        });
        wrap.append(b);
      }
      return wrap;
    }
    if (step.format === "number") {
      const input = h("input", { type: "number", inputMode: "decimal", step: "any", id: "answer", placeholder: step.unit || "" });
      const check = h("button", { type: "submit", className: "primary", textContent: "Check" });
      const form = h("form", { className: "row" }, h("label", { htmlFor: "answer", className: "sr-only", textContent: "Your answer" }), input, h("span", { textContent: step.unit || "" }), check);
      form.addEventListener("submit", (e) => {
        e.preventDefault();
        const v = parseFloat(input.value);
        if (Number.isNaN(v)) return say(fb, "bad", "Type a number first.");
        if (Math.abs(v - step.answer) <= step.tolerance) { check.disabled = input.disabled = true; correct(fb, step); }
        else wrong(fb, `${v > step.answer ? "Too big" : "Too small"}. Work through it one step at a time and check each one.`);
      });
      setTimeout(() => input.focus(), 0);
      return form;
    }
    if (step.format === "slider") {
      const s = step.slider;
      const decimals = String(s.step).split(".")[1]?.length || 0;
      const range = h("input", { type: "range", min: s.min, max: s.max, step: s.step, id: "slider" });
      range.value = s.min + (s.max - s.min) * 0.25;
      const out = h("output", { htmlFor: "slider" });
      const show = () => { out.value = `${Number(range.value).toFixed(decimals)} ${step.unit}`; scene.update && scene.update(s.param, Number(range.value)); };
      const nudge = (dir) => { range.value = (Number(range.value) + dir * s.step).toFixed(decimals); show(); };
      const minus = h("button", { type: "button", textContent: "−", ariaLabel: "Decrease" });
      const plus = h("button", { type: "button", textContent: "+", ariaLabel: "Increase" });
      minus.addEventListener("click", () => nudge(-1));
      plus.addEventListener("click", () => nudge(1));
      range.addEventListener("input", show);
      const check = h("button", { type: "button", className: "primary", textContent: "Launch" });
      check.addEventListener("click", () => {
        const v = Number(range.value);
        if (Math.abs(v - step.answer) <= step.tolerance + 1e-9) { [range, minus, plus, check].forEach((x) => (x.disabled = true)); correct(fb, step); }
        else wrong(fb, v > step.answer ? "A little less. Watch where it lands, then adjust." : "A little more. Watch where it lands, then adjust.");
      });
      show();
      return h("div", {}, h("div", { className: "slider-row" }, minus, range, plus, out), h("div", { className: "row" }, check));
    }
    if (step.format === "mix") {
      const status = h("p", { className: "help", textContent: "Use the cups above. The drink is checked after every move." });
      scene.bench.enable((strengths, moves) => {
        status.textContent = moves ? `${moves} move${moves === 1 ? "" : "s"}` : "Use the cups above. The drink is checked after every move.";
        if (scene.bench.matches(strengths, step.answer)) correct(fb, step);
      });
      document.getElementById("scene").scrollIntoView({ behavior: matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth", block: "nearest" });
      return status;
    }
    return h("p", { textContent: `Unknown step type: ${step.format}` });
  }

  function finish() {
    const key = `streak:${fwId}-${level}`;
    const streak = firstTry ? store.get(key, 0) + 1 : 0;
    store.set(key, streak);
    const nextLevel = `?f=${fwId}&level=${level + 1}`;
    const another = h("button", { type: "button", className: "primary", textContent: "Another one like this" });
    another.addEventListener("click", next);
    const msg = firstTry ? `Solved on the first try. That's ${streak} in a row.` : "Solved. Try another to get it first time.";
    const row = h("div", { className: "row" }, another);
    $("task").replaceChildren(h("p", { className: "feedback good", textContent: msg }), row);
    another.focus();
    if (streak >= 3) {
      fetch(`../bank/${fwId}-${level + 1}.json`, { method: "HEAD" }).then((r) => {
        if (r.ok) row.append(h("a", { href: nextLevel, className: "button", textContent: `Ready for level ${level + 1}` }));
      }).catch(() => {});
    }
  }

  if (fwId) start(); else picker();
})();
